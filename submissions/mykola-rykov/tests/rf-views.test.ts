import { expect, test } from 'vitest';
import { evaluateRfView, viewLocations } from '../src/rf/views';
import { rfViewSchema, parseWorkerResponse } from '../src/contracts/worker';
import { AnalysisCache } from '../src/rf/analysis';
import { newMission } from '../src/mission/defaults';
import { terrainFixture } from './fixtures/contracts';
import { createProjection } from '../src/terrain/coordinates';
import { projectRfPath } from '../src/mission/rf-path';
import type { TerrainStore } from '../src/terrain/store';
import type { JobContext } from '../src/workers/lifecycle';
const attitude = { headingDeg: 90, pitchDeg: 0, rollDeg: 0 };
const slice = { kind: 'slice' as const, columns: 4, rows: 3, minXM: 50, maxXM: 1000, minYM: 4500, maxYM: 4650, altitudeM: 100, attitude };
test('view coordinates, altitude rows, path distance and grid limits are explicit', () => {
  const heatmap = { kind: 'heatmap' as const, columns: 3, rows: 3, minimumAltitudeM: 100, maximumAltitudeM: 300, attitude, path: [{ xM: 0, yM: 0, altitudeM: 100 }, { xM: 100, yM: 0, altitudeM: 100 }, { xM: 100, yM: 100, altitudeM: 100 }] };
  const grid = viewLocations(heatmap);
  expect(grid.totalM).toBe(200); expect(grid.locations[1]).toEqual({ xM: 100, yM: 0, altitudeM: 300 });
  expect(grid.locations[7]).toEqual({ xM: 100, yM: 0, altitudeM: 100 });
  expect(() => rfViewSchema.parse({ ...slice, columns: 64, rows: 64 })).toThrow('2048');
  expect(() => rfViewSchema.parse({ ...slice, minXM: 1000 })).toThrow('ordered');
});
test('RF view projection reports invalid geometry as a recoverable local result', () => {
  const manifest = terrainFixture(), store = { manifest } as TerrainStore, mission = newMission(manifest);
  mission.launch.position.latitudeDeg = Number.NaN;
  const failed = projectRfPath(mission, null, store);
  expect(failed.path).toEqual([]); expect(failed.error).toContain('Invalid input');
  mission.launch.position.latitudeDeg = 46.2;
  const recovered = projectRfPath(mission, null, store);
  expect(recovered.error).toBeNull(); expect(recovered.path).toHaveLength(2);
});
test('RF views share validated ray propagation, preserve unknown cells and honour cancellation', async () => {
  const manifest = terrainFixture(); manifest.projectedBounds = { minXM: 0, maxXM: 7680, minYM: 0, maxYM: 7680 };
  const tile = { display: new Int16Array(65536), obstruction: new Int16Array(65536), validity: new Uint8Array(65536).fill(1) };
  const store = { manifest, get: async () => tile } as unknown as TerrainStore, mission = newMission(manifest);
  mission.launch.position = createProjection(manifest).inverse({ xM: 15, yM: 4665 }); mission.assumptions.terrainHeightUncertaintyM = 0;
  const context: JobContext = { jobId: 'view-job', checkpoint: async () => {}, progress: () => {}, emit: () => {} }, cache = new AnalysisCache();
  const before = parseWorkerResponse(await evaluateRfView(mission, mission.equipment[0]!.id, slice, store, context, cache));
  if (before.type !== 'view-grid') throw new Error('fixture');
  expect(new Uint8Array(before.validityBuffer).every(v => v === 1)).toBe(true);
  expect(before.assumptions.join(' ')).toContain('heading 90°');
  const misses = cache.propagationMisses;
  mission.equipment[0]!.uplink.transmitPowerDbm += 3; mission.equipment[0]!.downlink.transmitPowerDbm += 3;
  const after = await evaluateRfView(mission, mission.equipment[0]!.id, slice, store, context, cache);
  expect(cache.propagationMisses).toBe(misses);
  expect(new Float32Array(after.marginBuffer)[5]! - new Float32Array(before.marginBuffer)[5]!).toBeCloseTo(3, 4);
  expect(() => parseWorkerResponse({ ...after, validityBuffer: new ArrayBuffer(1) })).toThrow('dimensions');
  tile.validity[100 * 256 + 10] = 0;
  const missing = await evaluateRfView(mission, mission.equipment[0]!.id, slice, store, context);
  expect(new Uint8Array(missing.validityBuffer).some(v => v === 0)).toBe(true);
  context.checkpoint = async () => { throw new Error('cancelled'); };
  await expect(evaluateRfView(mission, mission.equipment[0]!.id, slice, store, context)).rejects.toThrow('cancelled');
});
