import { expect, test } from '@playwright/test';
import { readFile } from 'node:fs/promises';
test('offline route search, verified comparisons, export, cancellation and qualified no-result', async ({ page, context }) => {
  test.setTimeout(90_000);
  const external: string[] = [], errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await context.route('**/*', route => { const url = new URL(route.request().url()); if (url.hostname !== '127.0.0.1') { external.push(url.href); return route.abort(); } return route.continue(); });
  await page.goto('/');
  await page.getByLabel('Destination longitude', { exact: true }).fill('13.703');
  await page.getByText('Aircraft, radio and constraints', { exact: true }).click();
  await page.getByRole('button', { name: 'Use illustrative fixed-wing profile' }).click();
  await page.getByText('Complete mission configuration and files', { exact: true }).click();
  await page.getByRole('button', { name: 'Load configuration into editor' }).click();
  const input = page.getByLabel('Mission JSON', { exact: true }), config = JSON.parse(await input.inputValue());
  for (const point of [config.launch, config.destination]) point.altitude = { ...point.altitude, metres: 1500, reference: 'datum' };
  config.groundAntennaHeightAboveSurfaceM = 100;
  config.constraints.minimumAltitude = { ...config.launch.altitude, metres: 500 };
  config.constraints.maximumAltitude = { ...config.launch.altitude, metres: 2000 };
  config.constraints.minimumTerrainClearanceM = 20;
  config.constraints.corridorWidthM = 2000;
  await input.fill(JSON.stringify(config)); await page.getByRole('button', { name: 'Apply configuration', exact: true }).click();
  await page.getByRole('button', { name: 'Find verified route alternatives', exact: true }).click();
  await expect(page.getByTestId('scenario-card').first()).toBeVisible({ timeout: 30_000 });
  await expect(page.getByRole('button', { name: 'Cancel analysis', exact: true })).toHaveCount(0, { timeout: 45_000 });
  await expect(page.getByTestId('rf-result-status')).toContainText('Overall: feasible');
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export scenario results JSON', exact: true }).click();
  const download = await downloadPromise, path = await download.path();
  const exported = JSON.parse(await readFile(path!, 'utf8'));
  expect(exported.mission.constraints.corridorWidthM).toBe(2000);
  expect(exported.results.every((result: { feasibility: { status: string }; assumptions: string[] }) => result.feasibility.status === 'feasible' && result.assumptions.some(a => a.includes('Final analytic geometry verified')))).toBe(true);
  await page.getByRole('button', { name: 'Find verified route alternatives', exact: true }).click();
  await page.getByRole('button', { name: 'Cancel analysis', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Cancel analysis', exact: true })).toHaveCount(0);
  config.aircraft.batteryCapacityWh = 1;
  await input.fill(JSON.stringify(config)); await page.getByRole('button', { name: 'Apply configuration', exact: true }).click();
  await page.getByRole('button', { name: 'Find verified route alternatives', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('No feasible route was found within the 2 km corridor', { timeout: 30_000 });
  await expect(page.getByRole('alert')).toContainText('250 m horizontal / 50 m vertical');
  await expect(page.getByTestId('scenario-card')).toHaveCount(0);
  expect(external).toEqual([]); expect(errors).toEqual([]);
});
